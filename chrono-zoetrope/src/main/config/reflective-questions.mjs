// 프롬프트에 들어갈 마크다운 목록으로 변환.
// 본질문 뒤에 꼬리 질문을 함께 실어, 유령이 대답을 듣고 다음 턴에 이어가게 한다.
// 질문마다 id(P1-2 = 과거 1번째 결의 2번째 질문)를 붙인다 — 유령이 응답 JSON의 q 필드로
// 방금 쓴 질문 id를 보고하면 서버가 추적해, 이미 쓴 질문에는 "(이미 던졌다)" 표시를 박는다.
// 쓴 질문을 목록에서 지우지 않는 이유: 꼬리 질문은 본질문을 쓴 다음 턴에 이어가야 하므로.
export function renderQuestions(list, prefix = '', usedIds = []) {
  return list
    .map((q, gi) => {
      const items = (q.questions || []).map((item, qi) => {
        const id = `${prefix}${gi + 1}-${qi + 1}`
        const used = usedIds.includes(id)
        const mark = used ? ' **(이미 던졌다 — 본질문을 다시 쓰지 마라. 꼬리만 이어갈 수 있다)**' : ''
        const tails = (item.tails || []).map((t) => `"${t}"`).join(', ')
        return tails
          ? `  - (id: ${id}) "${item.q}"${mark}\n    ↳ 꼬리: ${tails}`
          : `  - (id: ${id}) "${item.q}"${mark}`
      })
      return `- **${q.label}**\n${items.join('\n')}`
    })
    .join('\n')
}
