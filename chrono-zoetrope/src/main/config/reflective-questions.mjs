// 프롬프트에 들어갈 마크다운 목록으로 변환.
// 본질문 뒤에 꼬리 질문을 함께 실어, 유령이 대답을 듣고 다음 턴에 이어가게 한다.
export function renderQuestions(list) {
  return list
    .map((q) => {
      const items = (q.questions || []).map((item) => {
        const tails = (item.tails || []).map((t) => `"${t}"`).join(', ')
        return tails
          ? `  - "${item.q}"\n    ↳ 꼬리: ${tails}`
          : `  - "${item.q}"`
      })
      return `- **${q.label}**\n${items.join('\n')}`
    })
    .join('\n')
}
